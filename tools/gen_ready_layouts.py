"""Generates the "ready" layouts (workout loaded, not started) from the workout layouts.

field_ready_karoo.xml <- field_interval_karoo.xml (Karoo style is the only style)

Everything stays the same (top row with gear and heart rate, the Next up box used as "First up",
the chart) except the upper part, which becomes: live watts (smaller), a big START WORKOUT button
in the middle, and the workout's name and total time. Design: docs/design/start-workout/ (B).

Run after changing a workout layout, before tools/gen_theme_overrides.py (from the repo root).
"""
import pathlib, re
root = pathlib.Path(__file__).resolve().parents[1]
layouts = root / 'app/src/main/res/layout'

STYLES = {
    'field_ready_karoo.xml': dict(
        src='field_interval_karoo.xml', watts_font='sans-serif', watts_style='normal',
        watts_extra='\n                android:letterSpacing="-0.05"\n                android:textScaleX="0.9"',
        label_font='ibm-plex-sans-condensed', label_style='normal', label_caps='true',
        total_font='sans-serif-medium', total_style='normal',
        start_bg='@drawable/progress_start_karoo', start_fg='@color/karoo_yellow_fg'),
}

UPPER = '''        <!-- Upper part (ready): live watts, START WORKOUT in the middle, the workout's name and
             total time. Generated by tools/gen_ready_layouts.py. -->
        <LinearLayout
            android:id="@+id/upper"
            android:layout_width="match_parent"
            android:layout_height="0dp"
            android:layout_weight="1"
            android:orientation="vertical"
            android:paddingStart="8dp"
            android:paddingTop="8dp"
            android:paddingEnd="8dp"
            android:paddingBottom="3dp">

        <!-- Watts (live, while you ride before starting), smaller than on the workout screen -->
        <FrameLayout
            android:layout_width="match_parent"
            android:layout_height="0dp"
            android:layout_weight="1">

            <TextView
                android:fontFamily="{watts_font}"
                android:id="@+id/watts"
                android:layout_width="match_parent"
                android:layout_height="match_parent"
                android:autoSizeMaxTextSize="80sp"
                android:autoSizeMinTextSize="28sp"
                android:autoSizeStepGranularity="2sp"
                android:autoSizeTextType="uniform"
                android:gravity="center"
                android:includeFontPadding="false"
                android:maxLines="1"
                android:paddingTop="26dp"
                android:textColor="@color/text"
                android:textStyle="{watts_style}"{watts_extra} />
        </FrameLayout>

        <!-- START WORKOUT: ▶ above the words, the whole box is the button. During the start
             countdown: the seconds above TAP TO CANCEL, and the button fills with its darker
             colour as they run down. -->
        <FrameLayout
            android:id="@+id/btn_start"
            android:layout_width="match_parent"
            android:layout_height="96dp"
            android:contentDescription="@string/start_workout">

            <ProgressBar
                android:id="@+id/start_fill"
                style="@android:style/Widget.ProgressBar.Horizontal"
                android:layout_width="match_parent"
                android:layout_height="match_parent"
                android:max="1000"
                android:progressDrawable="{start_bg}" />

            <LinearLayout
                android:layout_width="match_parent"
                android:layout_height="match_parent"
                android:gravity="center"
                android:orientation="vertical">

                <ImageView
                    android:id="@+id/start_icon"
                    android:layout_width="28dp"
                    android:layout_height="28dp"
                    android:layout_marginBottom="4dp"
                    android:importantForAccessibility="no"
                    android:src="@drawable/ic_play_filled"
                    android:tint="{start_fg}" />

                <TextView
                    android:fontFamily="{total_font}"
                    android:id="@+id/start_count"
                    android:layout_width="wrap_content"
                    android:layout_height="wrap_content"
                    android:includeFontPadding="false"
                    android:maxLines="1"
                    android:textColor="{start_fg}"
                    android:textSize="44sp"
                    android:textStyle="bold"
                    android:visibility="gone" />

                <TextView
                    android:fontFamily="{label_font}"
                    android:id="@+id/start_label"
                    android:layout_width="wrap_content"
                    android:layout_height="wrap_content"
                    android:includeFontPadding="false"
                    android:maxLines="1"
                    android:text="@string/start_workout"
                    android:textAllCaps="true"
                    android:textColor="{start_fg}"
                    android:textSize="24sp"
                    android:textStyle="{label_style}" />
            </LinearLayout>
        </FrameLayout>

        <!-- The workout's name and total time, baseline-aligned like the interval row -->
        <LinearLayout
            android:layout_width="match_parent"
            android:layout_height="wrap_content"
            android:layout_marginTop="10dp"
            android:layout_marginBottom="6dp"
            android:baselineAligned="true"
            android:orientation="horizontal">

            <TextView
                android:fontFamily="{label_font}"
                android:id="@+id/ready_name"
                android:layout_width="0dp"
                android:layout_height="wrap_content"
                android:layout_weight="1"
                android:ellipsize="end"
                android:includeFontPadding="false"
                android:maxLines="1"
                android:textAllCaps="{label_caps}"
                android:textColor="@color/text"
                android:textSize="15sp"
                android:textStyle="{label_style}" />

            <TextView
                android:fontFamily="{total_font}"
                android:id="@+id/ready_total"
                android:layout_width="wrap_content"
                android:layout_height="wrap_content"
                android:layout_marginStart="8dp"
                android:includeFontPadding="false"
                android:maxLines="1"
                android:textColor="@color/text"
                android:textSize="21sp"
                android:textStyle="{total_style}" />
        </LinearLayout>
        </LinearLayout>

'''

for out, st in STYLES.items():
    s = (layouts / st['src']).read_text()
    a = s.index('        <!-- Upper part')
    b = s.index('        <!-- Lower part')
    upper = UPPER
    for k, v in st.items():
        upper = upper.replace('{' + k + '}', v)
    s = s[:a] + upper + s[b:]
    # theme-override ids are per layout: th_interval_karoo_7 -> th_ready_karoo_7 etc.
    s = re.sub(r'@\+id/th_interval_', '@+id/th_ready_', s)
    s = s.replace('<!--\n', '<!--\n  GENERATED by tools/gen_ready_layouts.py from ' + st['src'] + '. Do not edit by hand.\n', 1)
    (layouts / out).write_text(s)
    print('wrote', out)
