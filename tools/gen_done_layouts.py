"""Generates the "workout done" layouts: field_done.xml and field_done_karoo.xml.

A big green check, "Workout done!", the workout's name, four tiles with the workout's own numbers
(time, average power, NP, average heart rate or cadence), a DONE button and a note that the ride
keeps recording. No heart rate row. The gear button is copied from the workout layout of the same
style. Design: docs/design/start-workout/ (done screen, mix of A and B).

Run after changing it, before tools/gen_theme_overrides.py (from the repo root).
"""
import pathlib, re
root = pathlib.Path(__file__).resolve().parents[1]
layouts = root / 'app/src/main/res/layout'

STYLES = {
    'field_done.xml': dict(src='field_interval.xml', label_font='sans-serif', label_style='bold', caps='false',
        value_font='sans-serif', value_style='bold', value_extra='', button_bg='@drawable/bg_done',
        button_fg='@color/resume_fg', label_color='@color/text_secondary'),
    'field_done_karoo.xml': dict(src='field_interval_karoo.xml', label_font='ibm-plex-sans-condensed', label_style='normal',
        caps='true', value_font='sans-serif', value_style='normal',
        value_extra='\n                    android:letterSpacing="-0.05"\n                    android:textScaleX="0.9"',
        button_bg='@drawable/bg_done_karoo', button_fg='@color/karoo_yellow_fg', label_color='@color/text'),
}

def tile(i, label):
    # RemoteViews can't inflate Space: the gap between two tiles is the right tile's margin.
    gap = '\n                android:layout_marginStart="6dp"' if i % 2 == 0 else ''
    return f'''
            <FrameLayout
                android:id="@+id/done_tile_{i}"
                android:layout_width="0dp"
                android:layout_height="match_parent"
                android:layout_weight="1"{gap}
                android:background="@drawable/bg_tile_tonal"
                android:paddingStart="8dp"
                android:paddingTop="6dp"
                android:paddingEnd="8dp"
                android:paddingBottom="5dp">

                <TextView
                    android:fontFamily="{{label_font}}"
                    android:id="@+id/done_label_{i}"
                    android:layout_width="match_parent"
                    android:layout_height="wrap_content"
                    android:gravity="end"
                    android:includeFontPadding="false"
                    android:maxLines="1"
                    android:text="{label}"
                    android:textAllCaps="{{caps}}"
                    android:textColor="{{label_color}}"
                    android:textSize="13sp"
                    android:textStyle="{{label_style}}" />

                <TextView
                    android:fontFamily="{{value_font}}"
                    android:id="@+id/done_value_{i}"
                    android:layout_width="match_parent"
                    android:layout_height="wrap_content"
                    android:layout_gravity="bottom|end"
                    android:gravity="end|bottom"
                    android:includeFontPadding="false"
                    android:maxLines="1"
                    android:textColor="@color/text"
                    android:textSize="26sp"
                    android:textStyle="{{value_style}}"{{value_extra}} />
            </FrameLayout>'''

BODY = '''<?xml version="1.0" encoding="utf-8"?>
<!--
  GENERATED by tools/gen_done_layouts.py. Do not edit by hand.
  Workout done: shown when the last interval ends. DONE takes the workout off (free-ride screen);
  the ride keeps recording.
-->
<FrameLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@+id/field_root"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    android:background="@android:color/transparent">

    <LinearLayout
        android:id="@+id/content"
        android:layout_width="match_parent"
        android:layout_height="match_parent"
        android:gravity="center_horizontal"
        android:orientation="vertical"
        android:paddingStart="8dp"
        android:paddingTop="10dp"
        android:paddingEnd="8dp"
        android:paddingBottom="6dp">

        <ImageView
            android:id="@+id/done_check"
            android:layout_width="0dp"
            android:layout_height="0dp"
            android:layout_weight="1"
            android:adjustViewBounds="true"
            android:maxHeight="84dp"
            android:importantForAccessibility="no"
            android:scaleType="fitCenter"
            android:src="@drawable/ic_done_check" />

        <TextView
            android:fontFamily="{label_font}"
            android:id="@+id/done_title"
            android:layout_width="wrap_content"
            android:layout_height="wrap_content"
            android:layout_marginTop="8dp"
            android:includeFontPadding="false"
            android:maxLines="1"
            android:text="@string/workout_done"
            android:textAllCaps="{caps}"
            android:textColor="@color/text"
            android:textSize="26sp"
            android:textStyle="{label_style}" />

        <TextView
            android:fontFamily="{label_font}"
            android:id="@+id/done_name"
            android:layout_width="match_parent"
            android:layout_height="wrap_content"
            android:layout_marginTop="4dp"
            android:layout_marginBottom="10dp"
            android:ellipsize="end"
            android:gravity="center"
            android:includeFontPadding="false"
            android:maxLines="1"
            android:textAllCaps="{caps}"
            android:textColor="@color/text_secondary"
            android:textSize="14sp" />

        <LinearLayout
            android:layout_width="match_parent"
            android:layout_height="54dp"
            android:orientation="horizontal">
''' + tile(1, '@string/time') + '''
''' + tile(2, '@string/avg_power') + '''
        </LinearLayout>

        <LinearLayout
            android:layout_width="match_parent"
            android:layout_height="54dp"
            android:layout_marginTop="6dp"
            android:orientation="horizontal">
''' + tile(3, '@string/done_np') + '''
''' + tile(4, '@string/avg_hr') + '''
        </LinearLayout>

        <!-- DONE: the whole box is the button -->
        <FrameLayout
            android:id="@+id/btn_done"
            android:layout_width="match_parent"
            android:layout_height="60dp"
            android:layout_marginTop="10dp"
            android:background="{button_bg}"
            android:contentDescription="@string/done">

            <TextView
                android:fontFamily="{label_font}"
                android:layout_width="wrap_content"
                android:layout_height="wrap_content"
                android:layout_gravity="center"
                android:includeFontPadding="false"
                android:text="@string/done"
                android:textAllCaps="true"
                android:textColor="{button_fg}"
                android:textSize="26sp"
                android:textStyle="{label_style}" />
        </FrameLayout>

        <!-- The ride keeps recording: a red dot and a short note -->
        <LinearLayout
            android:layout_width="wrap_content"
            android:layout_height="wrap_content"
            android:layout_marginTop="10dp"
            android:layout_marginBottom="4dp"
            android:gravity="center_vertical"
            android:orientation="horizontal">

            <ImageView
                android:layout_width="8dp"
                android:layout_height="8dp"
                android:layout_marginEnd="6dp"
                android:importantForAccessibility="no"
                android:src="@drawable/dot_recording" />

            <TextView
                android:fontFamily="{label_font}"
                android:layout_width="wrap_content"
                android:layout_height="wrap_content"
                android:includeFontPadding="false"
                android:text="@string/ride_keeps_recording"
                android:textAllCaps="{caps}"
                android:textColor="@color/text_secondary"
                android:textSize="13sp" />
        </LinearLayout>
    </LinearLayout>

{gear}
</FrameLayout>
'''

for out, st in STYLES.items():
    src = (layouts / st['src']).read_text()
    m = re.search(r'    <FrameLayout\n        android:id="@\+id/btn_settings".*?\n    </FrameLayout>\n', src, re.S)
    gear = re.sub(r'@\+id/th_\w+', '@+id/done_gear_icon', m.group(0)).rstrip('\n')
    s = BODY.replace('{gear}', gear)
    for k, v in st.items():
        s = s.replace('{' + k + '}', v)
    (layouts / out).write_text(s)
    print('wrote', out)
